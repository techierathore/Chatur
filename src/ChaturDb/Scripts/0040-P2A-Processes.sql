-- [REQ-FN-049] The wording of every step of the twelve TechieFlow processes, read by Processes.
-- The steps and checks themselves are code (Chatur.Core.Processes.ProcessCatalogue); only the wording is a row,
-- so it can be corrected from Settings > Corrections without touching code (REQ-UI-046).
-- [REQ-FN-050] A started process: one ProcessRun row for the selected project; Process run reads it.
CREATE TABLE IF NOT EXISTS ProcessRun (
    RunId INTEGER CONSTRAINT PkProcessRun PRIMARY KEY,
    ProjectId INTEGER NOT NULL,
    ProcessCode TEXT NOT NULL,
    State TEXT NOT NULL,
    CurrentStep INTEGER NOT NULL,
    StartedUtc TEXT NOT NULL,
    EndedUtc TEXT NULL,
    CONSTRAINT FkProcessRunProject FOREIGN KEY (ProjectId) REFERENCES Project (ProjectId)
);

CREATE INDEX IF NOT EXISTS IXProcessRunProjectIdProcessCode ON ProcessRun (ProjectId, ProcessCode);

